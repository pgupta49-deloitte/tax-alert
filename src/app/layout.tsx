"use client"
import { useEffect } from 'react'
// import type { Metadata } from "next";
import { usePathname } from 'next/navigation'
import { Inter } from "next/font/google";
import "./globals.css";
import { PasscodeProvider } from "@/context/PasscodeContext";
import { TaxDetailsProvider } from "@/context/TaxDetailsContext";
import Header from "@/components/header/Header";
import Footer from "@/components/footer/Footer";
import Navbar from "@/components/navbar/Navbar";
import { MsalProvider } from "@azure/msal-react";
import { PublicClientApplication, EventType, IPublicClientApplication } from "@azure/msal-browser";
import { msalConfig } from "../utils/authConfig";
import { useClient } from '@/utils/useClient';


// Initialize msalInstance as IPublicClientApplication
export const msalInstance: IPublicClientApplication = new PublicClientApplication(msalConfig);

// Asynchronous initialization of msalInstance
async function initializeMsalInstance() {
  try {
    await msalInstance.initialize();
    const accounts = msalInstance.getAllAccounts();
    if (accounts.length > 0) {
      msalInstance.setActiveAccount(accounts[0]);
    }

    msalInstance.addEventCallback((event: any) => {
      if (event.eventType === EventType.LOGIN_SUCCESS && event.payload.account) {
        const account = event.payload.account;
        msalInstance.setActiveAccount(account);
      }
    });
  } catch (error) {
    console.error('Failed to initialize msalInstance:', error);
  }
}

initializeMsalInstance();

const inter = Inter({ subsets: ["latin"] });

// export const metadata: Metadata = {
//   title: "Tax Alert",
//   description: "Generated by Deloitte",
// };

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const isClient = useClient(false);
  const pathname = usePathname()
  const showHeaderAndFooter = !pathname.includes('/login');
  useEffect(() => {
    initializeMsalInstance(); // Ensure msalInstance is initialized on component mount
  }, []);

  return (isClient ?
    <html lang="en">
      <head>
        <title>Tax Alert</title>
      </head>
      <body className={`${!showHeaderAndFooter ? inter.className : 'flex flex-col h-screen'}`} >
        <PasscodeProvider>
          <TaxDetailsProvider>
            <MsalProvider instance={msalInstance}>
              {showHeaderAndFooter && <Header />}
              {showHeaderAndFooter && <Navbar />}
              <main className={`${!showHeaderAndFooter ? '' : 'flex overflow-y-auto relative items-center justify-center w-[1366px] h-[500px] top-[129px] bg-[#F6F6F6]'}`}> {children} </main>
              {showHeaderAndFooter && <Footer />}
            </MsalProvider>
          </TaxDetailsProvider>
        </PasscodeProvider>
      </body>
    </html>
    : null
  );
}
